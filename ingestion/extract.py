"""HTML → structured blocks (headings, paragraphs, lists/procedures, tables, FAQ Q/A pairs).

Noise removal: scripts, styles, header/nav/footer, forms, cookie banners, chat widgets, marketing
pop-ups. FAQ modals are *content* on Getnet's site (answers live in ``o-modal__text-content``), so they
are converted into FAQ blocks before generic modal removal. Numbered procedures are kept as one block
so they are never flattened into fragments.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Literal
from urllib.parse import urldefrag, urljoin

from bs4 import BeautifulSoup, Comment, Declaration, Doctype, NavigableString, ProcessingInstruction, Tag

BlockKind = Literal["heading", "paragraph", "list", "procedure", "table", "faq"]

_NOISE_TAGS = (
    "script",
    "style",
    "noscript",
    "header",
    "footer",
    "nav",
    "form",
    "iframe",
    "svg",
    "button",
    "template",
    "select",
    "input",
)
_NOISE_ATTR = re.compile(
    r"cookie|chatbot|ppchat|popup|overlay|breadcrumb|newsletter|share|social|rota-fuga|cliente-direcionamento|"
    r"cliente-app|gnt-header|c-footer|skip-link|menu|navbar|banner-app|modal-fuga|whatsapp-float|lgpd",
    re.IGNORECASE,
)
_WS = re.compile("[ \t\u00a0\u200b]+")
_HEADINGS = {"h1": 1, "h2": 2, "h3": 3, "h4": 4}
_INLINE = {"span", "a", "strong", "em", "b", "i", "font", "label", "small", "sup", "sub", "u", "mark", "code"}


@dataclass
class Block:
    kind: BlockKind
    text: str
    level: int = 0
    question: str | None = None


@dataclass
class ExtractedDocument:
    url: str
    title: str
    canonical_url: str
    language: str | None
    blocks: list[Block] = field(default_factory=list)
    links: list[str] = field(default_factory=list)

    @property
    def text(self) -> str:
        return "\n".join(b.text for b in self.blocks)


def clean_text(text: str) -> str:
    lines = [_WS.sub(" ", ln).strip() for ln in text.replace("\r", "").split("\n")]
    return "\n".join(ln for ln in lines if ln).strip()


def _inline(node: Tag) -> str:
    return clean_text(node.get_text(" ", strip=True))


def _attr_text(tag: Tag) -> str:
    classes = tag.get("class") or []
    return " ".join([*(classes if isinstance(classes, list) else [str(classes)]), str(tag.get("id") or "")])


def _extract_faq_pairs(soup: BeautifulSoup) -> list[tuple[Tag, Block]]:
    pairs: list[tuple[Tag, Block]] = []
    # Getnet pattern: <a class="c-more-answers__question" data-modal=N>Q</a> + modal with the answer.
    for modal in soup.select(".o-modal__content--faq"):
        title = modal.select_one(".o-modal__title")
        body = modal.select_one(".o-modal__text-content") or modal.select_one(".o-modal__text")
        if title and body:
            q, a = _inline(title), clean_text(body.get_text("\n", strip=True))
            if q and a:
                pairs.append((modal, Block("faq", f"Pergunta: {q}\nResposta: {a}", question=q)))
    # Generic accordions: <details><summary>Q</summary>A</details>
    for det in soup.find_all("details"):
        summ = det.find("summary")
        if isinstance(summ, Tag):
            q = _inline(summ)
            summ.extract()
            a = clean_text(det.get_text("\n", strip=True))
            if q and a:
                pairs.append((det, Block("faq", f"Pergunta: {q}\nResposta: {a}", question=q)))
    # Definition lists used as FAQs
    for dl in soup.find_all("dl"):
        for dt in dl.find_all("dt"):
            dd = dt.find_next_sibling("dd")
            if isinstance(dd, Tag):
                q, a = _inline(dt), clean_text(dd.get_text("\n", strip=True))
                if q and a:
                    pairs.append((dl, Block("faq", f"Pergunta: {q}\nResposta: {a}", question=q)))
    return pairs


def _table_text(table: Tag) -> str:
    rows = []
    for tr in table.find_all("tr"):
        cells = [_inline(c) for c in tr.find_all(["th", "td"])]
        if any(cells):
            rows.append(" | ".join(cells))
    return "\n".join(rows)


def _list_block(lst: Tag) -> Block | None:
    items = [_inline(li) for li in lst.find_all("li", recursive=False)]
    items = [i for i in items if i]
    if not items:
        return None
    if lst.name == "ol":
        items = [_LEADING_NUM.sub("", i) for i in items]
        return Block("procedure", "\n".join(f"{n}. {i}" for n, i in enumerate(items, 1)))
    return Block("list", "\n".join(f"- {i}" for i in items))


_PLACEHOLDER = re.compile(r"javascript will|generated by script|^\s*(desktop|mobile|open|voltar)\s*$", re.IGNORECASE)
_LEADING_NUM = re.compile(r"^\s*(\d{1,2}[.)]|[•·-])\s*")
_STEP = re.compile(r"^\s*(\d{1,2})[).\-]\s+")


def _walk(node: Tag, out: list[Block], faq_nodes: dict[int, Block], buffer: list[str]) -> None:
    def flush() -> None:
        text = clean_text(" ".join(buffer))
        buffer.clear()
        if text:
            out.append(Block("paragraph", text))

    for child in list(node.children):
        if isinstance(child, NavigableString):
            if child.strip() and not _PLACEHOLDER.search(child):
                buffer.append(str(child))
            continue
        if not isinstance(child, Tag):
            continue
        if id(child) in faq_nodes:
            flush()
            out.append(faq_nodes[id(child)])
            continue
        name = child.name or ""
        if name in _HEADINGS:
            flush()
            text = _inline(child)
            if text:
                out.append(Block("heading", text, level=_HEADINGS[name]))
        elif name == "p":
            flush()
            text = clean_text(child.get_text(" ", strip=True))
            if text:
                out.append(Block("paragraph", text))
        elif name in ("ul", "ol"):
            flush()
            block = _list_block(child)
            if block:
                out.append(block)
        elif name == "table":
            flush()
            text = _table_text(child)
            if text:
                out.append(Block("table", text))
        elif name == "br":
            flush()
        elif name in _INLINE:
            buffer.append(child.get_text(" ", strip=True))
        else:
            flush()
            _walk(child, out, faq_nodes, buffer)
            flush()


def _merge_procedures(blocks: list[Block]) -> list[Block]:
    """Join consecutive '1) … 2) …' paragraphs into one procedure block (never fragment a procedure)."""
    out: list[Block] = []
    for b in blocks:
        if (
            b.kind == "paragraph"
            and _STEP.match(b.text)
            and out
            and out[-1].kind in ("procedure", "paragraph")
            and (out[-1].kind == "procedure" or _STEP.match(out[-1].text.split("\n")[-1]))
        ):
            prev = out.pop()
            out.append(Block("procedure", f"{prev.text}\n{b.text}"))
        else:
            out.append(b)
    return out


def _dedupe(blocks: list[Block]) -> list[Block]:
    seen: set[str] = set()
    out = []
    for b in blocks:
        key = b.text.lower()
        if key in seen:
            continue
        # FAQ questions also appear as bare links/paragraphs next to their modal: drop the bare copy.
        seen.add(key)
        out.append(b)
    questions = {b.question.lower() for b in out if b.question}
    return [b for b in out if not (b.kind in ("paragraph", "heading") and b.text.lower() in questions)]


def extract_html(html: str, url: str) -> ExtractedDocument:
    soup = BeautifulSoup(html, "lxml")
    title_tag = soup.find("title")
    title = _inline(title_tag) if isinstance(title_tag, Tag) else url
    title = re.sub(r"\s*[-|–]\s*Getnet.*$", "", title).strip() or title
    canonical = url
    link = soup.find("link", rel="canonical")
    if isinstance(link, Tag) and link.get("href"):
        canonical = urldefrag(urljoin(url, str(link["href"])))[0]
    html_tag = soup.find("html")
    lang = str(html_tag.get("lang"))[:2].lower() if isinstance(html_tag, Tag) and html_tag.get("lang") else None

    links: list[str] = []
    for a in soup.find_all("a", href=True):
        href = str(a["href"]).strip()
        if href.startswith(("mailto:", "tel:", "javascript:", "#")):
            continue
        links.append(urldefrag(urljoin(url, href))[0])

    for node in soup.find_all(string=lambda t: isinstance(t, (Comment, Declaration, Doctype, ProcessingInstruction))):
        node.extract()
    faq_pairs = _extract_faq_pairs(soup)
    # Remove bare FAQ question anchors (their text is carried by the FAQ block).
    for a in soup.select(".c-more-answers__question"):
        a.decompose()
    for tag in soup.find_all(_NOISE_TAGS):
        tag.decompose()
    for tag in soup.find_all(True):
        if tag.parent is None or tag.decomposed:
            continue
        if _NOISE_ATTR.search(_attr_text(tag)) and not tag.select_one(".o-modal__content--faq"):
            tag.decompose()

    faq_nodes = {id(node): block for node, block in faq_pairs if not node.decomposed}
    body = soup.body or soup
    blocks: list[Block] = []
    _walk(body, blocks, faq_nodes, [])
    # FAQ blocks whose node was not reached by the walk (e.g. nested oddly) are appended.
    present = {id(b) for b in blocks}
    blocks.extend(b for _, b in faq_pairs if id(b) not in present)
    blocks = _dedupe(_merge_procedures([b for b in blocks if len(b.text) > 1]))
    return ExtractedDocument(url=url, title=title, canonical_url=canonical, language=lang, blocks=blocks, links=links)


def remove_boilerplate(docs: list[ExtractedDocument], max_share: float = 0.3, min_docs: int = 5) -> int:
    """Drop blocks repeated across many pages (menus/footers that survived tag-based cleaning)."""
    html_docs = [d for d in docs if not d.url.lower().endswith(".pdf")]
    if len(html_docs) < min_docs:
        return 0
    counts: dict[str, int] = {}
    for d in html_docs:
        for key in {b.text for b in d.blocks if b.kind != "faq"}:
            counts[key] = counts.get(key, 0) + 1
    threshold = max(3, int(len(html_docs) * max_share))
    noisy = {k for k, c in counts.items() if c >= threshold}
    removed = 0
    for d in html_docs:
        before = len(d.blocks)
        d.blocks = [b for b in d.blocks if b.kind == "faq" or b.text not in noisy]
        removed += before - len(d.blocks)
    return removed
